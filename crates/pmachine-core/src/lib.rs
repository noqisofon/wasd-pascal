//! p-machineインタプリタ: `wasd-pcode`が生成するp-code（[`wasd_pcode::PCodeModule`]）
//! を実際に実行する。
//!
//! # このクレートが実装するオペコードは、タスク依頼の想定と異なる
//!
//! 本クレートの実装を指示したタスク依頼（Step 13）は、`wasd-pcode`が
//! `SLDC`/`LDCB`/`LDCI`/`LDCN`/`LOD`/`LAO`/`SRO`/`LDL`/`LLA`/`STL`/
//! `LAND`/`LOR`/`LNOT`/`BNOT`/`ABI`/`INCI`/`DECI`/`EQUI`/`NEQI`/`LEQI`/
//! `GEQI`/`TJP`/`JPL`/`FJPL`のような、実機の命令セットに近い粒度の
//! オペコードを既に発行している前提で書かれていた。しかし実際の
//! `wasd_pcode::opcode`モジュール（Step 11/12で実装済み）を確認したところ、
//! 実際に発行されるオペコードはそれとは異なる、より簡略化されたセット
//! （[`wasd_pcode::UnconfirmedOp`]の`Ldc`/`Lod`/`Str`/`Lda`/`Ind`/`Sti`/
//! `Adi`/`Sbi`/`Mpi`/`Dvi`/`Mod`/`Ngi`/`Equ`/`Neq`/`Leq`/`Geq`/
//! `And`/`Ior`/`Not`/`Ujp`/`Fjp`/`Stp`、および[`wasd_pcode::ConfirmedOp`]の
//! `Cpl`/`Cpg`/`Cpi`/`Scpi1`/`Scpi2`/`Rpu`/`Cxg`）だった
//! （`crates/wasd-pcode/src/opcode.rs`のドキュメント参照。特に
//! `LOD`/`STR`/`LDA`はグローバル用・ローカル用に分かれておらず、レベル差
//! [`wasd_pcode::Level`]を取る汎用形1本で統一されている）。
//!
//! これは「一次資料と実装が食い違う」というケースではなく、「タスク
//! 依頼の記述が、実際に存在するクレートの現状を正確に反映していな
//! かった」というケースである。実行すべき対象は実際に`wasd-pcode`が
//! 生成するp-codeそのものである以上、本クレートは**実際に存在する
//! オペコードセット**を対象に実装する。この経緯を後続セッションが
//! 混乱しないよう、ここに明記する。
//!
//! # ジャンプ命令のオフセット解釈について
//!
//! タスク依頼はジャンプ命令のオフセット解釈（二次資料由来の`JTAB`間接
//! 参照説）を一次資料由来の情報より優先しないよう注意していたが、実際に
//! 確認したところ、この論点は本クレートには（現状は）関係しない。
//! `wasd_pcode::CodeAddress`は「実バイト列オフセット」ではなく
//! 「命令列（`Vec<Instruction>`）中のインデックス」を保持する設計で
//! 既に確定している（`crates/wasd-pcode/src/opcode.rs`の`CodeAddress`の
//! ドキュメント、および`crates/wasd-pcode/src/text.rs`のテスト参照）。
//! 実バイト列へのエンコーディングは今回のスコープ外（将来の実バイナリ
//! 生成ステップ）のままであり、本クレートはIRレベルの命令列を直接
//! 解釈するインタプリタなので、`UJP`/`FJP`は単純に`self.ipc =
//! target.0 as usize`という代入で実装する（正負や`JTAB`の出る幕がない）。
//!
//! # メモリモデル: 単一の活性化レコード用スタックと、MSCWの扱い
//!
//! [`PMachine`]は`stack: Vec<i16>`という単一の連続領域に、グローバル
//! データ領域（アドレス`0..global_data_words`、常駐）と、その上に
//! 積まれる各呼び出しの活性化レコード（ローカル変数・一時変数領域＋
//! パラメータ領域＋（`FUNCTION`なら）戻り値領域）および式評価用の
//! 一時値を保持する。これは実機の「スタックとヒープが主記憶内で互いに
//! 向かって伸びる」という設計（Internal Architecture Guide, II.1.1.2）
//! のうち、本クレートのスコープ外であるヒープ（`NEW`/`DISPOSE`）を除いた
//! スタック側だけを`Vec<i16>`で素直に表現したものである。
//!
//! ただし、活性化レコード先頭のマーク・スタック制御ワード（MSCW、5ワード:
//! `MSSTAT`/`MSDYN`/`MSIPC`/`MSENV`/`MSPROC`）そのものは、`stack`上の
//! 実際の5ワードとしては確保・格納**しない**。その正確なバイト内容・
//! エンコーディングは一次資料未確認であり、本クレートが実際に必要と
//! するのは「静的リンクを辿ってレベル差アドレッシングを解決できること」
//! と「`RPU`実行時に呼び出し元のMP/IPCへ戻れること」の2点だけである。
//! そこで[`FrameRecord`]という別テーブル（Rust側の構造体、`stack`とは
//! 別領域）にこの2点の情報だけを保持する。`wasd-pcode`の
//! `CodeGenerator`が採番するアドレス（`Address(5)`始まり。
//! `crates/wasd-pcode/src/codegen.rs`の「活性化レコードのレイアウト」
//! ドキュメント参照）とのつじつまを合わせるため、[`FrameRecord::base`]は
//! 「アドレス5が指す実際の`stack`上の位置」として定義し、アドレス値から
//! そのまま`5`を引いた分だけ`base`にオフセットする（
//! [`PMachine`]の`addr_index`参照）。この「MSCWをメモリ上の実データとしては
//! 持たない」という選択は、タスク依頼の`PMachine`の設計例（メモリモデルは
//! `Vec<i16>`等で抽象化してよい、という指示）の範囲内での実装上の判断で
//! ある。
//!
//! # 呼び出し規約: パラメータの物理的な並べ替えについて
//!
//! `wasd-pcode`の呼び出し元コードは、`CPG`等の呼び出し命令を発行する
//! **前**に、仮引数の値（または`VAR`仮引数ならアドレス）を評価スタックへ
//! 積む（`crates/wasd-pcode/src/codegen.rs`の`gen_call_args`参照）。
//! 一方、同クレートが採用する活性化レコードのレイアウトは「マーク・
//! スタック→ローカル変数・一時変数領域→パラメータ領域」という順（低
//! アドレスから高アドレスへ）であり、パラメータ領域はローカル変数
//! 領域より**高い**オフセットに置かれる。
//!
//! この2つを素朴に組み合わせると矛盾する: 呼び出し元が先に積んだ
//! パラメータは物理的にスタックの**低い**位置に来るはずなのに、レイア
//! ウト上はローカル変数領域より**高い**位置にあるべきだからである
//! （呼び出し元がまだ使っている可能性のある、より低いアドレスの領域を
//! 呼び出し先のマーク・スタックやローカル変数として横取りすることは
//! できない）。
//!
//! そこで[`PMachine`]の呼び出し命令の実装（`call`関数）は、
//! [`wasd_pcode::PCodeModule::routines`]（[`wasd_pcode::RoutineMeta`]。
//! 実機のプロシージャ辞書に相当する簡略化。同型のドキュメント参照）から
//! 呼び出し先のパラメータ語数を引き、既に積まれているパラメータの値を
//! 一旦スタックから取り除いてから、マーク・スタック相当の空き（本クレートは
//! 上記の通り実データとしては確保しない）とローカル変数・一時変数領域
//! （ゼロ初期化）を新たに積み、その**後**でパラメータの値を積み直す
//! （必要なら関数の戻り値スロットも1ワード追加する）。これにより、
//! `wasd-pcode`が採番したアドレスオフセットと、実際に`stack`上でその
//! アドレスが指す位置とが一致する。
//!
//! `RPU <b>`は逆に、活性化レコードの先頭（`base`、アドレス5が指す位置）
//! から`b`ワード分を取り除き、それより上に残っていた分（`FUNCTION`の
//! 戻り値、存在する場合は1ワード）をそのまま呼び出し元に見える位置まで
//! 詰める。
//!
//! # タスク4: `RPU`の`b`パラメータの検証結果
//!
//! `crates/wasd-pcode/src/codegen.rs`の`emit_rpu`が採用する方針A
//! （`b = DATASIZE + パラメータ領域のワード数`）を上記の呼び出し規約で
//! 実行した場合、`RPU`実行後のスタックの高さは常に「呼び出し前の高さ
//! （`PROCEDURE`の場合）」または「呼び出し前の高さ+1（`FUNCTION`の場合、
//! 戻り値が1ワード残る）」に一致することを、`tests/rpu_b_verification.rs`
//! のテスト（`sp`を呼び出し前後で比較するアサーション、単純呼び出し・
//! 値引数・`VAR`引数・再帰呼び出しの組み合わせ）で確認した。方針Aは
//! **本クレートの実行モデル内ではCONFIRMED**として扱ってよい
//! （`crates/wasd-pcode/src/opcode.rs`の`ConfirmedOp::Rpu`のドキュメント
//! も参照。ただし実機バイナリでの検証ではなく、あくまで本プロジェクトの
//! 簡略化されたIR・本クレートのインタプリタ実装内での自己無矛盾性の
//! 検証である点に注意）。
//!
//! # Step 14: `WriteLn`向けのKERNELセグメント組み込みエミュレーション
//!
//! 一次資料（SofTech Microsystems, *UCSD p-System and UCSD Pascal Version
//! IV: Internal Architecture Guide*, Section III.1-III.2）によれば、
//! `WriteLn`/`ReadLn`のような言語レベルのI/O呼び出しはp-machineの専用
//! オペコードではなく、コンパイラ+OSがKERNELユニット（全コンパイル単位から
//! `segment 1`として常にアクセス可能）の`UNITWRITE`/`UNITREAD`ルーチン
//! 呼び出しに変換する、という階層構造になっている（`wasd_pcode::builtin`
//! モジュールドキュメント参照）。
//!
//! 本格的なRSP/IO・BIOS階層の完全再現は本プロジェクトの当面のスコープを
//! 大きく超えるため、[`PMachine::call_external`]/[`PMachine::call_builtin_kernel`]
//! は「`CXG`でKERNELセグメントへ呼び出す」という形だけを借りた**意図的な
//! 簡略化**として実装した: 正式な`UNITWRITE`のパラメータディスクリプタ等は
//! 一切再現せず、`wasd-pcode`独自の簡易procedure番号
//! （`BUILTIN_WRITELN_INT`/`BUILTIN_WRITELN_BOOL`/`BUILTIN_WRITELN_NONE`）を
//! 見て、対応する出力をRustの`Write`実装へ直接書き込むだけの単純な
//! エミュレーションを行う。KERNEL以外のセグメント（正式なUNIT呼び出し）は
//! 今回のスコープ外として`RuntimeError::UnimplementedOpcode`を返す。
//!
//! テスト可能性のため、[`PMachine`]の出力先は[`PMachine::with_output`]で
//! 任意の`Box<dyn std::io::Write>`へ差し替え可能にした（[`PMachine::new`]は
//! 標準出力に固定で書き込む従来の簡易実装のまま）。これはタスク依頼が
//! 明示的に許可した「テスト可能性のための正当な変更」に該当する。

